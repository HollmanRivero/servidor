-- 1. MAKE YOURSELF AN IMMORTAL ADMIN
UPDATE users 
SET role = 'admin', is_banned = FALSE 
WHERE username = 'YOUR_USERNAME';


-- 2. GRANT A 1-YEAR SUBSCRIPTION (When a friend pays 30€)
INSERT INTO subscriptions (user_id, status, started_at, expires_at, payment_method, notes)
VALUES (
    (SELECT id FROM users WHERE username = 'FRIEND_USERNAME'),
    'active',
    NOW(),
    NOW() + INTERVAL '1 year',
    'revolut', -- or vipps, stripe, cash
    'Paid 30€ for 1 year peace pass'
)
ON CONFLICT (user_id) DO UPDATE 
SET status = 'active',
    started_at = NOW(),
    expires_at = NOW() + INTERVAL '1 year',
    notes = EXCLUDED.notes;


-- 3. THE BAN HAMMER (Instant lockout)
UPDATE users 
SET is_banned = TRUE, 
    ban_reason = 'Disturbed my peace. Think again.',
    banned_at = NOW()
WHERE username = 'OFFENDER_USERNAME';

UPDATE subscriptions 
SET status = 'banned'
WHERE user_id = (SELECT id FROM users WHERE username = 'OFFENDER_USERNAME');


-- 4. FORGIVE & UNBAN (If they paid up and behaved)
UPDATE users 
SET is_banned = FALSE, ban_reason = NULL, banned_at = NULL 
WHERE username = 'OFFENDER_USERNAME';


-- 5. LIST ALL CUSTOMERS: WHO PAID, WHO'S ACTIVE, AND WHO'S BANNED
SELECT 
    u.username,
    u.role,
    CASE 
        WHEN u.is_banned THEN '🔨 BANNED (' || COALESCE(u.ban_reason, 'No reason') || ')'
        WHEN u.role = 'admin' THEN '👑 ADMIN (Permanent)'
        WHEN s.expires_at > NOW() THEN '✅ ACTIVE (Expires ' || TO_CHAR(s.expires_at, 'YYYY-MM-DD') || ')'
        WHEN s.expires_at IS NULL THEN '⏳ PENDING PAYMENT (Unpaid)'
        ELSE '❌ EXPIRED'
    END AS subscription_status,
    s.payment_method,
    u.created_at
FROM users u
LEFT JOIN subscriptions s ON u.id = s.user_id
ORDER BY u.created_at DESC;


